def get_svg_data(name: str, color: str = "#64748B") -> str:
    template = SVG_DATA.get(name, SVG_DATA["file-text" if "file-text" in SVG_DATA else "manuscript"])
    return template.format(color=color)


def get_pixmap(name: str, color: str = "#64748B", size: int = 18) -> QPixmap:
    """Generates a crisp QPixmap from the SVG string at high DPI resolution."""
    raw_svg = get_svg_data(name, color)
    byte_array = QByteArray(raw_svg.encode("utf-8"))
    renderer = QSvgRenderer(byte_array)

    pixmap = QPixmap(size * 2, size * 2)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
    renderer.render(painter)
    painter.end()

    pixmap.setDevicePixelRatio(2.0)
    return pixmap


def get_icon(name: str, color: str = "#64748B", size: int = 18) -> QIcon:
    """Returns a QIcon for buttons, trees, or menus."""
    return QIcon(get_pixmap(name, color, size))


def export_all_svgs(output_dir: str):
    """Writes static SVG files to the assets/icons folder for external reference."""
    os.makedirs(output_dir, exist_ok=True)
    for name, svg_tpl in SVG_DATA.items():
        svg_content = svg_tpl.format(color="#64748B")
        file_path = os.path.join(output_dir, f"{name}.svg")
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(svg_content)
